"""Generate Rust's std140 uniform layout from preserved original GLSL."""
from pathlib import Path
import os
import re
import subprocess
import shutil
import argparse

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'reference/original/assets/watery/shaders/common.glsl'
OUT = ROOT / 'src/uniforms.rs'

def generate():
    source = SOURCE.read_text(encoding='utf-8')
    constants = dict(re.findall(r'^#define (MAX_\w+) (\d+)$', source, re.M))
    block = source.split('uniform Globals {', 1)[1].split('} G;', 1)[0]
    offset = 0
    fields = []
    for line in block.strip().splitlines():
        m = re.fullmatch(r'\s*(ivec4|vec4|mat4) (\w+)(?:\[([^\]]+)\])?;', line)
        if not m:
            raise ValueError(f'Unsupported std140 field: {line}')
        ty, name, count = m.groups()
        rust_type, size = {'ivec4': ('[i32; 4]', 16), 'vec4': ('[f32; 4]', 16), 'mat4': ('[[f32; 4]; 4]', 64)}[ty]
        if count:
            factors = count.split(' * ')
            count = 1
            for factor in factors:
                count *= int(constants.get(factor, factor))
            rust_type = f'[{rust_type}; {count}]'
            size *= count
        fields.append((name, rust_type, offset, size))
        offset += size
    lines = ['//! Exact std140 layout from original common.glsl; matrices are column-major.',
             '//! Generated by tools/generate_uniforms.py. No unsafe casts are used.',
             '#[allow(non_snake_case)]', '#[repr(C, align(16))]', '#[derive(Clone, Debug)]',
             'pub struct Globals {']
    for name, ty, _, _ in fields:
        lines.append(f'    pub {name}: {ty},')
    lines += ['}', 'impl Globals {', f'    pub const BYTE_SIZE: usize = {offset};',
              '    /// Construct explicit zeroed values; caller must populate simulation and camera fields.',
              '    pub fn zeroed() -> Self {', '        Self {']
    for name, ty, _, _ in fields:
        count = ty.count('[')
        if ty == '[[f32; 4]; 4]':
            val = '[[0.0; 4]; 4]'
        elif count == 2:
            n = ty.rsplit('; ', 1)[1].rstrip(']')
            val = f'[[0.0; 4]; {n}]'
        else:
            val = '[0; 4]' if ty.startswith('[i32') else '[0.0; 4]'
        lines.append(f'            {name}: {val},')
    lines += ['        }', '    }', '    /// Serialize without allocation into an existing GPU upload staging slice.',
              '    pub fn write_le(&self, out: &mut [u8]) -> Result<(), usize> {',
              '        if out.len() != Self::BYTE_SIZE { return Err(Self::BYTE_SIZE); }']
    for name, ty, off, size in fields:
        if ty.count('[') == 2:
            lines.append(f'        for (i, value) in self.{name}.iter().flatten().enumerate() {{')
        else:
            lines.append(f'        for (i, value) in self.{name}.iter().enumerate() {{')
        base = f'{off} + ' if off else ''
        lines.append(f'            out[{base}i * 4..{base}(i + 1) * 4].copy_from_slice(&value.to_le_bytes());')
        lines.append('        }')
    lines += ['        Ok(())', '    }', '}', '#[cfg(test)]', 'mod tests {', '    use super::*;',
              '    #[test]', '    fn every_field_matches_original_std140_offsets() {',
              f'        assert_eq!(std::mem::size_of::<Globals>(), {offset});',
              '        assert_eq!(std::mem::align_of::<Globals>(), 16);']
    for name, _, off, _ in fields:
        lines.append(f'        assert_eq!(std::mem::offset_of!(Globals, {name}), {off});')
    lines += ['    }', '    #[test]', '    fn upload_is_little_endian_and_preserves_matrix_columns() {',
              '        let mut g = Globals::zeroed();', '        g.dims = [1, -2, 3, 4];',
              '        g.proj[1][2] = 1.25;', '        g.sources[63][3] = -4.0;',
              '        let mut out = vec![0xFF; Globals::BYTE_SIZE];',
              '        assert_eq!(g.write_le(&mut out), Ok(()));',
              '        assert_eq!(&out[4..8], &(-2_i32).to_le_bytes());']
    for name, index, val in [('proj', 6, '1.25_f32'), ('sources', 255, '-4.0_f32')]:
        off = next(off for n, _, off, _ in fields if n == name) + index * 4
        lines.append(f'        assert_eq!(&out[{off}..{off + 4}], &({val}).to_le_bytes());')
    lines += ['        assert_eq!(g.write_le(&mut []), Err(Globals::BYTE_SIZE));',
              '    }', '}', '']
    rustfmt = shutil.which('rustfmt')
    if not rustfmt and os.name == 'nt':
        candidate = Path(r'K:\Rust\.rustup\toolchains\stable-x86_64-pc-windows-msvc\bin\rustfmt.exe')
        if candidate.is_file():
            rustfmt = str(candidate)
    if not rustfmt:
        raise RuntimeError('rustfmt was not found; install the component from rust-toolchain.toml')
    formatted = subprocess.run([rustfmt, '--edition', '2024', '--emit', 'stdout'], input='\n'.join(lines),
                               text=True, capture_output=True, check=True).stdout
    return formatted.replace('\r\n', '\n')

if __name__ == '__main__':
    p = argparse.ArgumentParser()
    p.add_argument('--check', action='store_true')
    args = p.parse_args()
    output = generate()
    if args.check:
        if OUT.read_text(encoding='utf-8') != output:
            raise SystemExit('Uniform layout differs; regenerate')
    else:
        OUT.write_text(output, encoding='utf-8', newline='\n')
    print('PASS: original std140 Globals layout generated/verified')
