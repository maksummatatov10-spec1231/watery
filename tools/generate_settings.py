"""Translate only the straight-line Watery static default initializer, failing closed.
The javap dump is reference input; this is not a general Java decompiler.
"""
import argparse
import os
from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'reference/bytecode/me.blue.client.water.WaterSettings.txt'
OUT = ROOT / 'src/settings.rs'

def generate():
    text = SOURCE.read_text(encoding='utf-8')
    fields = re.findall(r'^  public static (int|float|boolean|java\.lang\.String) (\w+);', text, re.M)
    initial = text.split('  static {};', 1)[1]
    stack = []
    values = {}
    for line in initial.splitlines():
        m = re.match(r'\s+\d+: (\w+)(?:\s+(.*))?$', line)
        if not m:
            continue
        op, arg = m.group(1), m.group(2) or ''
        if op.startswith(('iconst_', 'fconst_')):
            stack.append(op.split('_')[1] + ('.0' if op.startswith('fconst_') else ''))
        elif op in ('bipush', 'sipush'):
            stack.append(str(int(arg)))
        elif op in ('ldc', 'ldc_w'):
            if '// float ' in arg:
                number = arg.split('// float ', 1)[1].removesuffix('f')
                stack.append(number)
            elif '// String' in arg:
                value = arg.split('// String', 1)[1].strip()
                if value:
                    raise ValueError('Unexpected nonempty String constant')
                stack.append('String::new()')
            else:
                raise ValueError(f'Unsupported constant: {line}')
        elif op == 'putstatic':
            field = re.search(r'// Field (\w+):', arg).group(1)
            if len(stack) != 1 or field in values:
                raise ValueError(f'Unexpected stack or duplicate for {field}')
            values[field] = stack.pop()
        elif op == 'invokestatic' and 'snapshot:' in arg:
            break
        else:
            raise ValueError(f'Unsupported initializer instruction: {line}')
    if set(values) != {name for _, name in fields}:
        raise ValueError('Not every declared public setting has exactly one initializer')
    types = {'int': 'i32', 'float': 'f32', 'boolean': 'bool', 'java.lang.String': 'String'}
    lines = ['//! Original Watery 1.2.2 defaults; generated by tools/generate_settings.py.',
             '//! Names intentionally match the original commands and configuration keys.',
             '#[allow(non_snake_case)]', '#[derive(Clone, Debug, PartialEq)]', 'pub struct Settings {']
    for ty, name in fields:
        lines.append(f'    pub {name}: {types[ty]},')
    lines += ['}', 'impl Default for Settings {', '    fn default() -> Self {', '        Self {']
    for ty, name in fields:
        value = values[name]
        if ty == 'boolean':
            if value not in ('0', '1'):
                raise ValueError('Nonboolean initializer')
            value = 'true' if value == '1' else 'false'
        lines.append(f'            {name}: {value},')
    lines += ['        }', '    }', '}', '', '#[cfg(test)]', 'mod tests {',
              '    use super::*;', '    #[test]', '    fn original_material_defaults_are_not_tuned_for_speed() {',
              '        let s = Settings::default();',
              '        assert_eq!([s.resolution, s.sandResolution, s.lavaResolution, s.slimeResolution], [6, 12, 6, 4]);',
              '        assert_eq!(s.gravity, 9.81);',
              '        assert_eq!([s.flipRatio, s.lavaFlipRatio, s.slimeFlipRatio], [0.99, 0.9993, 0.9]);',
              '        assert!(s.whitewater && s.wallFill && !s.sheetFill && !s.bucketMakesSource);',
              '        assert!(s.tntReactions && s.lavaIgniteFlammables);',
              '        assert_eq!(s.ffmpeg, "");', '    }', '}', '']
    rustfmt = shutil.which('rustfmt')
    if not rustfmt and os.name == 'nt':
        candidate = Path(r'K:\Rust\.rustup\toolchains\stable-x86_64-pc-windows-msvc\bin\rustfmt.exe')
        if candidate.is_file():
            rustfmt = str(candidate)
    if not rustfmt:
        raise RuntimeError('rustfmt was not found; install the component from rust-toolchain.toml')
    formatted = subprocess.run([rustfmt, '--edition', '2024', '--emit', 'stdout'], input='\n'.join(lines),
                               text=True, capture_output=True, check=True).stdout
    return formatted.replace('\r\n', '\n'), len(fields)

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output, count = generate()
    if args.check:
        if OUT.read_text(encoding='utf-8') != output:
            raise SystemExit('Generated settings differ from original bytecode; regenerate')
    else:
        OUT.write_text(output, encoding='utf-8', newline='\n')
    print(f'PASS: {count} typed settings exactly accounted for from original static initializer')
